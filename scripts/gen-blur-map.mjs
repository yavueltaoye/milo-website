/**
 * Generates a blurDataURL map for all project images.
 *
 * For each image in public/images/projects, creates a 16×10 (or 10×16)
 * WebP thumbnail encoded as base64, suitable for next/image placeholder="blur".
 *
 * Run: node scripts/gen-blur-map.mjs
 * Output: src/data/blurMap.ts
 */
import { readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const PUBLIC = path.resolve("public");
const IMG_ROOT = path.resolve(PUBLIC, "images/projects");
const OUT = path.resolve("src/data/blurMap.ts");
const BLUR_SIZE = 16;

async function* walk(dir) {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const p = path.join(dir, entry.name);
    if (entry.isDirectory()) yield* walk(p);
    else yield p;
  }
}

const EXT = new Set([".jpg", ".jpeg", ".png", ".webp"]);
const entries = [];

for await (const file of walk(IMG_ROOT)) {
  const ext = path.extname(file).toLowerCase();
  if (!EXT.has(ext)) continue;

  const meta = await sharp(file).metadata();
  const isLandscape = (meta.width ?? 1) >= (meta.height ?? 1);
  const w = isLandscape ? BLUR_SIZE : Math.round(BLUR_SIZE * (meta.width ?? 1) / (meta.height ?? 1));
  const h = isLandscape ? Math.round(BLUR_SIZE * (meta.height ?? 1) / (meta.width ?? 1)) : BLUR_SIZE;

  const buf = await sharp(file)
    .resize(Math.max(w, 1), Math.max(h, 1), { fit: "fill" })
    .webp({ quality: 20 })
    .toBuffer();

  const b64 = `data:image/webp;base64,${buf.toString("base64")}`;
  // Convert absolute path to public URL: /images/projects/...
  const url = "/" + path.relative(PUBLIC, file).replace(/\\/g, "/");
  entries.push([url, b64]);
  console.log(`✓ ${url}`);
}

entries.sort((a, b) => a[0].localeCompare(b[0]));

const lines = entries.map(([url, b64]) => `  "${url}": "${b64}",`).join("\n");
const output = `// Auto-generated by scripts/gen-blur-map.mjs — do not edit manually.
// Re-run after adding or replacing images in public/images/projects/.
export const blurMap: Record<string, string> = {
${lines}
};
`;

await writeFile(OUT, output, "utf8");
console.log(`\nWrote ${entries.length} blur placeholders → src/data/blurMap.ts`);
